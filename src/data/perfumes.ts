// Generate structured catalog to reach ~300 realistic perfume entries
function generateFullCatalog(): Perfume[] {
  const baseCatalog: Perfume[] = SEED_PERFUMES.map(p => ({
    ...p,
    dataStatus: 'prototype_to_verify',
    sourceType: 'mock',
    sourceName: 'AI-generated prototype dataset',
    externalId: null,
    lastVerified: null,
    imageStatus: 'placeholder',
    imageUrl: null,
    imageAttribution: null,
    notesConfidence: 'unverified'
  }));

  const generatedList: Perfume[] = [];
  let counter = 1;

  for (const b of BRANDS_EXTENDED) {
    for (const arch of SCENT_ARCHETYPES) {
      const id = `${b.brand.toLowerCase().replace(/[^a-z0-9]/g, '-')}-${arch.code}-${counter}`;
      
      // Check if already in base seed to avoid duplicates
      const exists = baseCatalog.some(p => p.id.startsWith(id.substring(0, 15)));
      if (exists && counter < 5) continue;

      const pLevel = (b.baseLevel || 2) as 1 | 2 | 3 | 4;
      const perf: Perfume = {
        id,
        name: `${arch.nameSuffix}`,
        nameZh: `${arch.nameSuffixZh}`,
        brand: b.brand,
        brandZh: b.brandZh,
        imagePlaceholder: {
          gradient: arch.gradient,
          silhouette: b.silhouette,
          accentColor: arch.accent
        },
        priceLevel: pLevel,
        priceRangeGBP: b.priceGBP,
        priceRangeRMB: b.priceRMB,
        fragranceFamily: arch.family,
        fragranceFamilyZh: arch.familyZh,
        topNotes: arch.top,
        topNotesZh: arch.topZh,
        middleNotes: arch.mid,
        middleNotesZh: arch.midZh,
        baseNotes: arch.base,
        baseNotesZh: arch.baseZh,
        tags: arch.tags,
        tagsZh: arch.tagsZh,
        seasons: arch.seasons,
        occasions: arch.occasions,
        mood: arch.mood,
        intensity: arch.intensity,
        sweetness: arch.sweetness,
        freshness: arch.freshness,
        genderExpression: 'unisex',
        description: `${b.brand}'s interpretation of ${arch.descEn}`,
        descriptionZh: `${b.brandZh}独家呈现的${arch.nameSuffixZh}：${arch.descZh}`,
        suitableFor: arch.suitableEn,
        suitableForZh: arch.suitableZh,
        avoidIf: arch.avoidEn,
        avoidIfZh: arch.avoidZh,
        beginnerFriendlyScore: +(8.5 + (counter % 14) * 0.1).toFixed(1),

        dataStatus: 'prototype_to_verify',
        sourceType: 'mock',
        sourceName: 'AI-generated prototype dataset',
        externalId: null,
        lastVerified: null,
        imageStatus: 'placeholder',
        imageUrl: null,
        imageAttribution: null,
        notesConfidence: 'unverified'
      };

      generatedList.push(perf);
      counter++;
      if (baseCatalog.length + generatedList.length >= 300) break;
    }
    if (baseCatalog.length + generatedList.length >= 300) break;
  }

  return [...baseCatalog, ...generatedList];
}

export const PERFUMES_DATA: Perfume[] = generateFullCatalog();
